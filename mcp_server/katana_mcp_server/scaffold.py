_SUPERTOOL_INIT = '''\
from .Node import {cls}
'''

_SUPERTOOL_NODE = '''\
"""SuperTool node definition for {name}.

Place the parent directory (the one containing the SuperTools folder) on
KATANA_RESOURCES, restart Katana, and the node type "{name}" becomes
available in the Tab menu.
"""

import PackageSuperToolAPI

from . import Editor


class {cls}(PackageSuperToolAPI.V2.Node):
    def __init__(self):
        super({cls}, self).__init__()
        self.addInputPort("in")
        self.addOutputPort("out")

        params = self.getParameters()
        params.createChildString("exampleParam", "default value")
        params.createChildNumber("exampleNumber", 1.0)

    def getEditor(self):
        return Editor.{cls}Editor(self)

    def apply(self, searchPattern="/root"):
        """Cook-time logic: modify the scene below searchPattern here."""
        pass
'''

_SUPERTOOL_EDITOR = '''\
"""Qt editor widget for the {name} SuperTool."""

try:
    from PySide6 import QtWidgets
except ImportError:
    from PySide2 import QtWidgets


class {cls}Editor(QtWidgets.QWidget):
    def __init__(self, node, parent=None):
        super({cls}Editor, self).__init__(parent)
        self._node = node

        layout = QtWidgets.QVBoxLayout(self)
        self._label = QtWidgets.QLabel("{name} - edit me in Editor.py")
        self._text = QtWidgets.QLineEdit()
        self._text.setPlaceholderText("exampleParam")
        self._text.editingFinished.connect(self._apply)

        current = node.getParameter("exampleParam")
        if current is not None:
            self._text.setText(str(current.getValue(0)))

        layout.addWidget(self._label)
        layout.addWidget(self._text)

    def _apply(self):
        param = self._node.getParameter("exampleParam")
        if param is not None:
            param.setValue(self._text.text(), 0)
'''


def scaffold_supertool(name, base_directory):
    """Create a PackageSuperToolAPI-based SuperTool skeleton under
    <base_directory>/SuperTools/<name>/. Add <base_directory> to
    KATANA_RESOURCES to load it."""
    cls = _sanitize_name(name)
    root = os.path.join(base_directory, "SuperTools", cls)
    files = {
        os.path.join(root, "__init__.py"): _SUPERTOOL_INIT.format(cls=cls),
        os.path.join(root, "Node.py"): _SUPERTOOL_NODE.format(name=cls,
                                                              cls=cls),
        os.path.join(root, "Editor.py"): _SUPERTOOL_EDITOR.format(name=cls,
                                                                  cls=cls),
    }
    written = [_write(p, c) for p, c in files.items()]
    return {"ok": True, "directory": os.path.abspath(root),
            "files": written,
            "activate": ("Add %r to KATANA_RESOURCES and restart Katana; "
                         "the node type %r appears in the Tab menu."
                         % (os.path.abspath(base_directory), cls))}


