"""Local scaffolding generators: launcher .bat files, project directory
layouts, SuperTool / panel / Python tool skeletons.

These run on the machine hosting the MCP server (no Katana connection
required) and write files to disk.
"""

import os
import re
import stat
import textwrap


def _sanitize_name(name):
    cleaned = re.sub(r"[^0-9A-Za-z_]+", "_", name).strip("_")
    if not cleaned:
        raise ValueError("Name %r has no usable characters" % name)
    if cleaned[0].isdigit():
        cleaned = "_" + cleaned
    return cleaned


def _write(path, content):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(textwrap.dedent(content).lstrip("\n"))
    return os.path.abspath(path)


