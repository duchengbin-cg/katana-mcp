def create_launcher_bat(katana_exe, output_path, project_path=None,
                        env_vars=None, katana_resources=None,
                        mcp_autostart=True, mcp_port=17820,
                        extra_args=None):
    """Write a Windows .bat that sets up the environment and starts Katana.

    katana_exe:      path to katanaBin.exe / katana.exe
    output_path:     where to write the .bat
    project_path:    optional .katana file to open
    env_vars:        dict of extra environment variables
    katana_resources: list of directories joined into KATANA_RESOURCES
    mcp_autostart:   add KATANA_MCP_AUTOSTART=1 so the bridge starts itself
    mcp_port:        KATANA_MCP_PORT value
    extra_args:      extra command line args appended to the Katana call
    """
    env_vars = dict(env_vars or {})
    if mcp_autostart:
        env_vars.setdefault("KATANA_MCP_AUTOSTART", "1")
        env_vars.setdefault("KATANA_MCP_PORT", str(mcp_port))

    lines = ["@echo off",
             "rem Generated by katana-mcp",
             "rem Launches Foundry Katana with a project environment.",
             ""]

    resources = list(katana_resources or [])
    if resources:
        joined = ";".join(resources)
        lines.append('set "KATANA_RESOURCES=%s;%%KATANA_RESOURCES%%"' % joined)

    for key in sorted(env_vars):
        lines.append('set "%s=%s"' % (key, env_vars[key]))

    cmd = '"%s"' % katana_exe
    if project_path:
        cmd += ' "%s"' % project_path
    if extra_args:
        cmd += " " + extra_args

    lines += ["", 'echo Starting Katana...', 'start "Katana" ' + cmd, ""]
    path = _write(output_path, "\r\n".join(lines) + "\r\n")
    return {"ok": True, "path": path,
            "preview": "\n".join(lines)}


