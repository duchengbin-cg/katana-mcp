_DEFAULT_LAYOUT = [
    "assets/models",
    "assets/textures",
    "assets/hdri",
    "assets/plates",
    "assets/cameras",
    "lookdev",
    "lighting",
    "lighting/templates",
    "renders",
    "comp",
    "scripts",
    "refs",
    "docs",
]


def scaffold_project_directory(base_path, layout=None, extra_dirs=None):
    """Create a VFX project directory tree. Returns the created paths."""
    dirs = list(layout or _DEFAULT_LAYOUT)
    dirs += list(extra_dirs or [])
    created = []
    for rel in dirs:
        path = os.path.join(base_path, rel)
        os.makedirs(path, exist_ok=True)
        created.append(os.path.abspath(path))
    return {"ok": True, "base": os.path.abspath(base_path),
            "created": created, "count": len(created)}


