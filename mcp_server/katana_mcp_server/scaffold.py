_PANEL_TEMPLATE = '''\
"""Katana tab: {name}

Katana discovers this file when its parent "Tabs" directory lives under a
KATANA_RESOURCES path. Open it via Tabs > {name}.
"""

try:
    from PySide6 import QtWidgets
except ImportError:
    from PySide2 import QtWidgets

from Katana import UI4


class {cls}Panel(UI4.Tabs.BaseTab):
    def __init__(self, parent):
        super({cls}Panel, self).__init__(parent)
        layout = QtWidgets.QVBoxLayout(self)
        layout.addWidget(QtWidgets.QLabel("{name} panel - build me!"))
        self._button = QtWidgets.QPushButton("Do something")
        self._button.clicked.connect(self._on_click)
        layout.addWidget(self._button)
        layout.addStretch(1)

    def _on_click(self):
        from Katana import NodegraphAPI
        root = NodegraphAPI.GetRootNode()
        print("{name}: root has %d children" % len(root.getChildren()))


PluginRegistry = [("KatanaPanel", 2, "{name}", {cls}Panel)]
'''


def scaffold_panel_tool(name, base_directory):
    """Create a Katana panel (tab) skeleton under <base_directory>/Tabs/."""
    cls = _sanitize_name(name)
    path = os.path.join(base_directory, "Tabs", cls + ".py")
    written = _write(path, _PANEL_TEMPLATE.format(name=cls, cls=cls))
    return {"ok": True, "file": written,
            "activate": ("Add %r to KATANA_RESOURCES and restart Katana; "
                         "open via Tabs > %s."
                         % (os.path.abspath(base_directory), cls))}


