_STARTUP_TOOL = '''\
"""Katana startup script: {name}

Lives in a "Startup" directory under a KATANA_RESOURCES path; runs once
when Katana launches.
"""


def register():
    from Katana import UI4
    mw = UI4.App.MainWindow.GetMainWindow()
    try:
        menubar = mw.menuBar()
    except AttributeError:
        return
    menu = menubar.addMenu("{name}")
    action = menu.addAction("Run {name}")
    action.triggered.connect(run)


def run():
    from Katana import NodegraphAPI
    root = NodegraphAPI.GetRootNode()
    print("{name} ran: %d root-level nodes" % len(root.getChildren()))


register()
'''

_SHELF_TOOL = '''\
"""Katana shelf / script tool: {name}

Run from Katana's Python shelf, or bind it to a menu with the Startup
scaffold. Keep logic in run() so it stays testable.
"""


def run():
    from Katana import NodegraphAPI

    selected = NodegraphAPI.GetAllSelectedNodes()
    if not selected:
        print("{name}: select at least one node first")
        return

    for node in selected:
        print("{name}: %s (%s)" % (node.getName(), node.getType()))
        # TODO: do the actual work here


if __name__ == "__main__":
    run()
'''


def scaffold_python_tool(name, base_directory, kind="startup"):
    """Create a Python tool skeleton. kind='startup' writes
    <base>/Startup/<name>.py (auto-registered menu). kind='shelf' writes
    <base>/Scripts/<name>.py (importable shelf/script tool)."""
    cls = _sanitize_name(name)
    if kind == "startup":
        path = os.path.join(base_directory, "Startup", cls + ".py")
        template = _STARTUP_TOOL
        activate = ("Add %r to KATANA_RESOURCES and restart Katana; a %r "
                    "menu appears." % (os.path.abspath(base_directory), cls))
    else:
        path = os.path.join(base_directory, "Scripts", cls + ".py")
        template = _SHELF_TOOL
        activate = ("Run inside Katana: import %s; %s.run()" % (cls, cls))
    written = _write(path, template.format(name=cls))
    return {"ok": True, "file": written, "activate": activate}


