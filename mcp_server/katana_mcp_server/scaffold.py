def default_templates_dir():
    return os.environ.get(
        "KATANA_MCP_TEMPLATES_DIR",
        os.path.join(os.path.expanduser("~"), ".katana-mcp", "templates"))


def template_path(name, directory=None):
    safe = _sanitize_name(name)
    return os.path.join(directory or default_templates_dir(),
                        safe + ".json")
